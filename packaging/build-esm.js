'use strict'
// Generates the native ES module entry point next to the CommonJS build:
//   dist/index.mjs   - re-exports every export of dist/index.js, plus the default export
//   dist/index.d.mts - the matching typings for TypeScript's node16/nodenext/bundler resolution
//
// The ES module entry wraps the CommonJS build instead of being a second copy of the library, so
// CommonJS and ES module consumers share one module instance. The named exports are read from the
// CommonJS build at build time, so the wrapper never needs to be kept in sync by hand. Explicit
// `export const` bindings (instead of `export * from './index.js'`) also work on Node versions that
// cannot detect the named exports of a CommonJS module.
//
// The wrapper must not depend on how the importer turns a CommonJS module into an ES module (F1). dist/index.js
// sets `__esModule` and `exports.default`, and tools disagree about what `import cjs from './index.js'` then is:
// - Node.js, webpack, esbuild and Rolldown (Vite 8 builds) give module.exports, which has every export;
// - Rollup's commonjs plugin, Vite SSR and vitest with inlined dependencies (server.deps.inline, ssr.noExternal)
//   apply the __esModule interop and give exports.default, the Substitute class. Their namespace import
//   (`import * as`) has the named exports instead.
// So the wrapper imports both, uses whichever one is the complete exports object, and fails loudly at import
// time if neither is (instead of exporting undefined values).
//
// Runs as part of `npm run build`, after tsc.

const fs = require('fs')
const path = require('path')

const dist = path.resolve(__dirname, '..', 'dist')
const entry = path.join(dist, 'index.js')
const cjs = require(entry)

if (!Object.prototype.hasOwnProperty.call(cjs, 'default')) {
  throw new Error(`${entry} has no default export`)
}

const identifier = /^[A-Za-z_$][\w$]*$/
const names = Object.keys(cjs).filter(name => name !== 'default').sort()
for (const name of names) {
  if (!identifier.test(name)) throw new Error(`Cannot re-export ${JSON.stringify(name)} from an ES module`)
}

// The typings re-export the default export under the name it has in index.d.ts (`export default Substitute`),
// so that `import Substitute from '@fluffy-spoon/substitute'` is the Substitute class for TypeScript, too.
const defaultName = names.find(name => cjs[name] === cjs.default)
if (defaultName === undefined) {
  throw new Error(`The default export of ${entry} is not also a named export; cannot type it in index.d.mts`)
}

const header = '// Generated by packaging/build-esm.js during `npm run build`. Do not edit.'
const packageJson = JSON.parse(fs.readFileSync(path.resolve(__dirname, '..', 'package.json'), 'utf8'))
const bugsUrl = packageJson.bugs && packageJson.bugs.url
if (typeof bugsUrl !== 'string') throw new Error('package.json has no bugs.url')
const interopFailure = `${packageJson.name}: the ES module entry could not read the exports of its CommonJS build (dist/index.js). ` +
  `Please report this at ${bugsUrl} and name the bundler or test runner you use. As a workaround, load the package with require().`

const mjs = [
  header,
  "import cjsDefault, * as cjsNamespace from './index.js';",
  '',
  '// The complete exports of dist/index.js: its default export is also its named export ' + JSON.stringify(defaultName) + '.',
  `const isCompleteExports = value => value != null && value.${defaultName} !== undefined && value.default === value.${defaultName};`,
  '// Node.js and most bundlers give module.exports as the default import; tools that apply the __esModule interop',
  '// give exports.default instead, and the named exports through the namespace. See packaging/build-esm.js.',
  'const cjs = isCompleteExports(cjsDefault) ? cjsDefault : isCompleteExports(cjsNamespace) ? cjsNamespace : undefined;',
  `if (cjs === undefined) throw new Error(${JSON.stringify(interopFailure)});`,
  '',
  ...names.map(name => `export const ${name} = cjs.${name};`),
  'export default cjs.default;',
  ''
].join('\n')

const dmts = [
  header,
  "export * from './index.js';",
  `export { ${defaultName} as default } from './index.js';`,
  ''
].join('\n')

fs.writeFileSync(path.join(dist, 'index.mjs'), mjs)
fs.writeFileSync(path.join(dist, 'index.d.mts'), dmts)
