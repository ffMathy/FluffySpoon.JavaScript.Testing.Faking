'use strict'
// Generates the native ES module entry point next to the CommonJS build:
//   dist/index.mjs   - re-exports every export of dist/index.js, plus the default export
//   dist/index.d.mts - the matching typings for TypeScript's node16/nodenext/bundler resolution
//
// The ES module entry wraps the CommonJS build instead of being a second copy of the library, so
// CommonJS and ES module consumers share one module instance. The named exports are read from the
// CommonJS build at build time, so the wrapper never needs to be kept in sync by hand. Explicit
// `export const` bindings (instead of `export * from './index.js'`) also work on Node versions that
// cannot detect the named exports of a CommonJS module.
//
// The wrapper must not depend on how the importer turns a CommonJS module into an ES module (F1, PK4-2).
// dist/index.js sets `__esModule` and `exports.default`, and tools disagree about what `import cjs from './index.js'`
// and `import * as cjs from './index.js'` then are:
// - Node.js, webpack, esbuild and Rolldown (Vite 8 builds) give module.exports as the default import, which has
//   every export;
// - Rollup's commonjs plugin, Vite SSR and vitest with inlined dependencies (server.deps.inline, ssr.noExternal)
//   apply the __esModule interop and give exports.default, the Substitute class, as the default import. Their
//   namespace import (`import * as`) has the named exports instead;
// - vitest with inlined dependencies and `deps.interopDefault: false` gives an object without the named exports
//   as the default import, and the named exports plus that object (not the Substitute class) as the namespace.
// So the wrapper imports both views and uses whichever one holds every named export with the type it has at build
// time. The default export takes no part in that decision: the wrapper's own default export is the named export
// that dist/index.js exports as its default (the Substitute class), found here at build time. If neither view is
// complete, the wrapper fails loudly at import time (instead of exporting undefined values).
//
// Runs as part of `npm run build`, after tsc.

const fs = require('fs')
const path = require('path')

const dist = path.resolve(__dirname, '..', 'dist')
const entry = path.join(dist, 'index.js')
const cjs = require(entry)

if (!Object.prototype.hasOwnProperty.call(cjs, 'default')) {
  throw new Error(`${entry} has no default export`)
}

const identifier = /^[A-Za-z_$][\w$]*$/
const names = Object.keys(cjs).filter(name => name !== 'default').sort()
for (const name of names) {
  if (!identifier.test(name)) throw new Error(`Cannot re-export ${JSON.stringify(name)} from an ES module`)
}

// The default export of dist/index.js is also one of its named exports (`export default Substitute`). The typings
// re-export it under that name, so that `import Substitute from '@fluffy-spoon/substitute'` is the Substitute class
// for TypeScript, too, and the ES module entry exports that named export as its default.
const defaultName = names.find(name => cjs[name] === cjs.default)
if (defaultName === undefined) {
  throw new Error(`The default export of ${entry} is not also a named export; cannot type it in index.d.mts`)
}
if (typeof cjs[defaultName] !== 'function') {
  throw new Error(`The default export of ${entry} (${defaultName}) is not a function`)
}

// The type of every named export, which a complete view of dist/index.js must reproduce (PK4-2).
const exportTypes = {}
for (const name of names) {
  if (cjs[name] === undefined) throw new Error(`The export ${name} of ${entry} is undefined`)
  exportTypes[name] = typeof cjs[name]
}

const header = '// Generated by packaging/build-esm.js during `npm run build`. Do not edit.'
const packageJson = JSON.parse(fs.readFileSync(path.resolve(__dirname, '..', 'package.json'), 'utf8'))
const bugsUrl = packageJson.bugs && packageJson.bugs.url
if (typeof bugsUrl !== 'string') throw new Error('package.json has no bugs.url')
const interopFailure = `${packageJson.name}: the ES module entry could not read the exports of its CommonJS build (dist/index.js). ` +
  `Please report this at ${bugsUrl} and name the bundler or test runner you use. As a workaround, load the package with require().`

const mjs = [
  header,
  "import cjsDefault, * as cjsNamespace from './index.js';",
  '',
  '// The type of every named export of dist/index.js, read at build time.',
  `const exportTypes = ${JSON.stringify(exportTypes)};`,
  '// A view of dist/index.js is complete when it holds every named export. Its own default export does not matter:',
  '// some tools hand over a namespace whose default is not the Substitute class. See packaging/build-esm.js.',
  'const isCompleteExports = value => value != null && Object.keys(exportTypes).every(name => typeof value[name] === exportTypes[name]);',
  '// Node.js and most bundlers give module.exports as the default import; tools that apply the __esModule interop',
  '// give exports.default (or another object) instead, and the named exports through the namespace.',
  'const cjs = isCompleteExports(cjsDefault) ? cjsDefault : isCompleteExports(cjsNamespace) ? cjsNamespace : undefined;',
  `if (cjs === undefined) throw new Error(${JSON.stringify(interopFailure)});`,
  '',
  ...names.map(name => `export const ${name} = cjs.${name};`),
  `export default cjs.${defaultName};`,
  ''
].join('\n')

const dmts = [
  header,
  "export * from './index.js';",
  `export { ${defaultName} as default } from './index.js';`,
  ''
].join('\n')

fs.writeFileSync(path.join(dist, 'index.mjs'), mjs)
fs.writeFileSync(path.join(dist, 'index.d.mts'), dmts)
