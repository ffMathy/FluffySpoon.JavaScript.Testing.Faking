'use strict'
// Generates the native ES module entry point next to the CommonJS build:
//   dist/index.mjs   - re-exports every export of dist/index.js, plus the default export
//   dist/index.d.mts - the matching typings for TypeScript's node16/nodenext/bundler resolution
//
// The ES module entry wraps the CommonJS build instead of being a second copy of the library, so
// CommonJS and ES module consumers share one module instance. The named exports are read from the
// CommonJS build at build time, so the wrapper never needs to be kept in sync by hand. Explicit
// `export const` bindings (instead of `export * from './index.js'`) also work on Node versions that
// cannot detect the named exports of a CommonJS module.
//
// Runs as part of `npm run build`, after tsc.

const fs = require('fs')
const path = require('path')

const dist = path.resolve(__dirname, '..', 'dist')
const entry = path.join(dist, 'index.js')
const cjs = require(entry)

if (!Object.prototype.hasOwnProperty.call(cjs, 'default')) {
  throw new Error(`${entry} has no default export`)
}

const identifier = /^[A-Za-z_$][\w$]*$/
const names = Object.keys(cjs).filter(name => name !== 'default').sort()
for (const name of names) {
  if (!identifier.test(name)) throw new Error(`Cannot re-export ${JSON.stringify(name)} from an ES module`)
}

// The typings re-export the default export under the name it has in index.d.ts (`export default Substitute`),
// so that `import Substitute from '@fluffy-spoon/substitute'` is the Substitute class for TypeScript, too.
const defaultName = names.find(name => cjs[name] === cjs.default)
if (defaultName === undefined) {
  throw new Error(`The default export of ${entry} is not also a named export; cannot type it in index.d.mts`)
}

const header = '// Generated by packaging/build-esm.js during `npm run build`. Do not edit.'

const mjs = [
  header,
  "import cjs from './index.js';",
  ...names.map(name => `export const ${name} = cjs.${name};`),
  'export default cjs.default;',
  ''
].join('\n')

const dmts = [
  header,
  "export * from './index.js';",
  `export { ${defaultName} as default } from './index.js';`,
  ''
].join('\n')

fs.writeFileSync(path.join(dist, 'index.mjs'), mjs)
fs.writeFileSync(path.join(dist, 'index.d.mts'), dmts)
